#!/usr/bin/env bash
# CN Project — Extension C: Backend B Service Isolation
# pf_setup.sh — idempotent script to load the Backend B isolation anchor
#
# ROLLBACK: run pf_rollback.sh in the same directory to remove these rules.
#
# USAGE: sudo bash pf_setup.sh
#
# Confirm MAC2_IP with Aditya (Mac 2 owner) before running.
# Current value from CN_PROJECT_LIVE_CONFIG.md: 10.7.11.31

set -euo pipefail

# ── Configuration ──────────────────────────────────────────────────────────
MAC2_IP="10.7.11.31"          # Mac 2 (nginx proxy) IP — confirm with Aditya
MAC4_IP="10.7.2.96"           # Mac 4 (this machine) IP
ANCHOR_NAME="com.cn-project.backend-b-isolation"
ANCHOR_FILE="/etc/pf.anchors/${ANCHOR_NAME}"
PF_CONF="/etc/pf.conf"
BACKUP_CONF="/etc/pf.conf.bak-cn-extension-c"
EVIDENCE_DIR="/Users/vaidehisahu/CN/evidence/phase2"
ANCHOR_RULES_SRC="${EVIDENCE_DIR}/pf_anchor.conf"

# ── Checks ─────────────────────────────────────────────────────────────────
if [ "$(id -u)" -ne 0 ]; then
  echo "ERROR: This script must be run as root (sudo)." >&2
  exit 1
fi

# ── Backup /etc/pf.conf if not already backed up ───────────────────────────
if [ ! -f "${BACKUP_CONF}" ]; then
  echo "[setup] Backing up ${PF_CONF} → ${BACKUP_CONF}"
  cp "${PF_CONF}" "${BACKUP_CONF}"
else
  echo "[setup] Backup already exists at ${BACKUP_CONF} — skipping."
fi

# ── Write the anchor rules file ────────────────────────────────────────────
echo "[setup] Writing anchor rules to ${ANCHOR_FILE}"
mkdir -p /etc/pf.anchors
cat > "${ANCHOR_FILE}" << RULES
# CN Project — Extension C anchor rules
# Generated by pf_setup.sh — do not edit by hand.
# To update: edit pf_setup.sh and re-run.

# Allow loopback access to port 3002
pass in quick on lo0 proto tcp to 127.0.0.1 port 3002

# Allow Mac 2 (nginx proxy, ${MAC2_IP}) inbound to port 3002
pass in quick on en0 proto tcp from ${MAC2_IP} to any port 3002

# Block all other inbound connections to port 3002
block in quick on en0 proto tcp to any port 3002
RULES

# ── Enable pf if not already enabled ───────────────────────────────────────
if ! pfctl -s info 2>/dev/null | grep -q 'Status: Enabled'; then
  echo "[setup] Enabling pf..."
  pfctl -e
fi

# ── Wire the anchor into /etc/pf.conf if not already present ───────────────
if ! grep -qF "${ANCHOR_NAME}" "${PF_CONF}"; then
  echo "[setup] Adding anchor reference to ${PF_CONF}"
  printf '\n# CN Extension C: Backend B isolation\nanchor "%s"\nload anchor "%s" from "%s"\n' \
    "${ANCHOR_NAME}" "${ANCHOR_NAME}" "${ANCHOR_FILE}" >> "${PF_CONF}"
else
  echo "[setup] Anchor already referenced in ${PF_CONF} — skipping."
fi

# ── Reload pf ──────────────────────────────────────────────────────────────
echo "[setup] Reloading pf rules from ${PF_CONF}"
pfctl -f "${PF_CONF}"

# ── Verify the anchor is loaded ────────────────────────────────────────────
echo "[setup] Active pf rules (anchor):"
pfctl -a "${ANCHOR_NAME}" -s rules 2>/dev/null || echo "WARNING: anchor not found after load"

echo
echo "[setup] Done. Backend B (port 3002) is now restricted to:"
echo "  - loopback (127.0.0.1)"
echo "  - Mac 2 nginx proxy (${MAC2_IP})"
echo
echo "To revert: sudo bash ${EVIDENCE_DIR}/pf_rollback.sh"
